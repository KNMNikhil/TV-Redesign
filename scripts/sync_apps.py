#!/usr/bin/env python3
"""Read the TV's installed apps and inputs and write them where the launcher can load them.

webOS does not let a third-party app list what is installed, so this runs on your computer instead:

    python scripts/sync_apps.py <TV_IP>            # writes app/apps.js and app/icons/
    python scripts/sync_apps.py <TV_IP> --list     # only print app ids and titles

The generated files describe your own TV and are not committed.
"""
import asyncio
import json
import os
import sys
import urllib.parse
import urllib.request

import tvlink

APP_DIR = os.path.join(tvlink.ROOT, "app")


def safe_name(app_id):
    return "".join(ch if ch.isalnum() or ch in "._-" else "_" for ch in app_id) + ".png"


def fetch_icon(url, host, ctx):
    """Icons come from the TV itself; anything served from elsewhere is skipped."""
    if urllib.parse.urlparse(str(url)).hostname != host:
        return None
    try:
        return urllib.request.urlopen(url, context=ctx, timeout=10).read()
    except Exception as err:   # an unreadable icon should not stop the sync
        print(f"  no icon ({err})")
        return None


async def main(host, list_only):
    ws = await tvlink.connect(host)
    try:
        points = (await tvlink.request(ws, "ssap://com.webos.applicationManager/listLaunchPoints")).get("launchPoints", [])
        inputs = (await tvlink.request(ws, "ssap://tv/getExternalInputList")).get("devices", [])
    finally:
        await ws.close()

    if list_only:
        for p in points:
            print(f'{p["id"]:45} {p["title"]}')
        return

    icon_dir = os.path.join(APP_DIR, "icons")
    os.makedirs(icon_dir, exist_ok=True)
    ctx = tvlink.tls_context()
    apps = []
    for p in points:
        if p.get("hidden"):
            continue
        url = p.get("largeIcon") if str(p.get("largeIcon", "")).startswith("http") else p.get("icon")
        data = fetch_icon(url, host, ctx)
        if data is None:
            continue
        name = safe_name(p["id"])
        with open(os.path.join(icon_dir, name), "wb") as f:
            f.write(data)
        apps.append({"id": p["id"], "title": p["title"], "icon": "icons/" + name})

    result = {
        "apps": apps,
        "inputs": [{"appId": d["appId"], "label": d.get("label") or d["id"]} for d in inputs if d.get("appId")],
    }
    with open(os.path.join(APP_DIR, "apps.js"), "w") as f:
        f.write("// Generated by scripts/sync_apps.py from your TV. Not committed.\n")
        f.write("window.TV_APPS = " + json.dumps(result, indent=1, ensure_ascii=False) + ";\n")
    print(f"Synced {len(apps)} apps and {len(result['inputs'])} inputs.")


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    host = args[0] if args else os.environ.get("TV_HOST")
    if not host:
        sys.exit("usage: sync_apps.py <TV_IP> [--list]")
    asyncio.run(main(host, "--list" in sys.argv))
